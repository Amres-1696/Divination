// 八卦符号到二进制映射
const TRIGRAM_TO_BINARY = {
    '☰': '111', '☱': '011', '☲': '101', '☳': '001',
    '☴': '110', '☵': '010', '☶': '100', '☷': '000'
};

// 构建卦象查找表：从6位二进制字符串映射到GUA条目
// 这样无论GUA数组的排列顺序如何，都能正确查找
const GUA_LOOKUP = {};
GUA.forEach((entry, idx) => {
    const symbols = entry[2]; // 例如 '☷☳'，第一个字符=上卦，第二个=下卦
    const upperBin = TRIGRAM_TO_BINARY[symbols[0]];
    const lowerBin = TRIGRAM_TO_BINARY[symbols[1]];
    const key = upperBin + lowerBin; // 6位二进制
    GUA_LOOKUP[key] = entry;
});

// 通过二进制字符串查找卦象（替代直接数组索引）
function lookupGua(fullBinary) {
    return GUA_LOOKUP[fullBinary] || GUA[0]; // 兜底返回坤卦
}


